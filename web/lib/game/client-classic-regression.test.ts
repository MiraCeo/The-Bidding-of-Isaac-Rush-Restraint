import { createHash } from 'node:crypto';
import { describe, expect, it } from 'vitest';
import baseline from './fixtures/classic-0.2.13-baseline.json';
import runtimeBaseline from './fixtures/classic-cross-runtime-baseline.json';
import {
  createCharacterSelectionState,
  clientGameReducer,
  type ClientGameState,
} from './client-session';
import type { CharacterId, PlayerTurn } from './item-types';
import { canonicalJson } from '../ui/replay-record';
import { saveCompatibility } from '../ui/game-version';

function hash(game: ClientGameState): string {
  return createHash('sha256')
    .update(canonicalJson(JSON.parse(JSON.stringify(game))))
    .digest('hex');
}
// Cross-runtime floating-point math differs in raw AI diagnostic weights only.
// These exact overrides
// were captured from 8ea001f, with all 780 old/current states equal per runtime.
// No game value is rounded and the original Windows transcript is untouched.
function expectedHash(key: string, original: string): string {
  return process.platform === 'linux'
    ? ((runtimeBaseline.linuxOverrides as Record<string, string>)[key] ??
        original)
    : original;
}

/** Captured before the refactor, never regenerated by the test under review. */
describe('classic 0.2.13 frozen pre-refactor state transcripts', () => {
  it('anchors the runtime variants to the unchanged original transcript and pre-refactor source', () => {
    expect(
      createHash('sha256').update(canonicalJson(baseline)).digest('hex'),
    ).toBe(runtimeBaseline.originalCanonicalSha256);
    expect(runtimeBaseline.classicFunctionalCommit).toBe(
      baseline.classicFunctionalCommit,
    );
    expect(runtimeBaseline.states).toBe(780);
    expect(Object.keys(runtimeBaseline.linuxOverrides)).toHaveLength(18);
    const keys = new Set(
      baseline.matches.flatMap((m) =>
        m.rooms.flatMap((_, i) =>
          ['result', 'ranking', 'contest'].map(
            (stage) => `${m.characterId}/${m.seed}/${i}/${stage}`,
          ),
        ),
      ),
    );
    for (const [key, value] of Object.entries(runtimeBaseline.linuxOverrides)) {
      expect(keys.has(key)).toBe(true);
      expect(value).toMatch(/^[a-f0-9]{64}$/);
    }
  });
  it('retains the old compatibility identity', () => {
    expect(baseline.compatibility).toBe('20-personality-client-1-818e3e55');
    expect(saveCompatibility).toBe(baseline.compatibility);
  });
  it.each(baseline.matches)(
    'preserves all phases for $characterId / seed $seed',
    (match) => {
      let game: ClientGameState = createCharacterSelectionState(match.seed);
      expect(hash(game)).toBe(match.selectionHash);
      game = clientGameReducer(game, {
        type: 'start_game',
        characterId: match.characterId as CharacterId,
      });
      expect(hash(game)).toBe(match.startHash);
      expect(match.rooms).toHaveLength(15);
      for (const [index, room] of match.rooms.entries()) {
        expect(hash(game), `entry ${index}`).toBe(room.entryHash);
        game = clientGameReducer(game, {
          type: 'submit_player_turn',
          turn: room.turn as PlayerTurn,
        });
        expect(hash(game), `result ${index}`).toBe(
          expectedHash(
            `${match.characterId}/${match.seed}/${index}/result`,
            room.resultHash,
          ),
        );
        game = clientGameReducer(game, {
          type: 'show_room_ranking',
          view: 'score',
        });
        expect(hash(game), `ranking ${index}`).toBe(
          expectedHash(
            `${match.characterId}/${match.seed}/${index}/ranking`,
            room.rankingHash,
          ),
        );
        game = clientGameReducer(game, {
          type: 'switch_room_ranking',
          view: 'contest',
        });
        expect(hash(game), `contest ${index}`).toBe(
          expectedHash(
            `${match.characterId}/${match.seed}/${index}/contest`,
            room.contestHash,
          ),
        );
        game = clientGameReducer(game, { type: 'advance_room' });
        expect(hash(game), `advance ${index}`).toBe(room.advancedHash);
      }
      expect(game.phase).toBe('game_result');
      game = clientGameReducer(game, { type: 'restart_game', seed: 99 });
      expect(hash(game)).toBe(match.restartedHash);
    },
  );
});
